#!/usr/bin/env python3
"""Embed the exact shipped UI assets; never maintain a second page copy in C."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
assets = {"welcome": "index.html", "system": "system.html", "network": "network.html",
          "about": "about.html", "files": "files.html", "bluetooth": "bluetooth.html", "css": "ui.css"}
lines = ["/* Generated by tools/embed-ui.py from assets/ui. */"]
for symbol, filename in assets.items():
    source = (ROOT / "assets/ui" / filename).read_text(encoding="utf-8")
    lines.append(f"static const char embedded_ui_{symbol}[] =")
    lines.extend("    " + json.dumps(line, ensure_ascii=False) for line in source.splitlines(keepends=True))
    lines.append(";")
target = Path(sys.argv[1])
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text("\n".join(lines) + "\n", encoding="utf-8")
