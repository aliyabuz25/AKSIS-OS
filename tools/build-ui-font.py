#!/usr/bin/env python3
"""Bake the bundled OFL Selawik font into grayscale kernel glyphs (Pillow)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
CHARS = ''.join(chr(i) for i in range(32, 127)) + 'ÇçĞğİıÖöŞşÜü·'

def main():
    output = ['/* Generated by tools/build-ui-font.py. Selawik source: assets/fonts/OFL.txt. */',
              '#ifndef UI_FONT_DATA_H', '#define UI_FONT_DATA_H']
    for index, size in enumerate((18, 26, 44)):
        font = ImageFont.truetype(str(ROOT / 'assets/fonts/selawk.ttf'), size*4)
        height = size + 8
        records, pixels = [], []
        for char in CHARS:
            advance = round(font.getlength(char)/4)
            width = max(advance + 2, (font.getbbox(char)[2]+3)//4 + 2)
            canvas = Image.new('L', (width*4, height*4))
            ImageDraw.Draw(canvas).text((4, 0), char, font=font, fill=255)
            canvas = canvas.resize((width,height),Image.Resampling.LANCZOS)
            records.append(f'{{{ord(char)},{width},{advance},{len(pixels)}}}')
            pixels.extend(canvas.tobytes())
        output.append(f'static const ui_glyph_t glyphs_{index}[] = {{' + ','.join(records) + '};')
        output.append(f'static const uint8_t alpha_{index}[] = {{')
        output.extend(','.join(str(x) for x in pixels[i:i+32])+',' for i in range(0,len(pixels),32))
        output.append('};')
    output += ['static const ui_font_t fonts[] = {',
               *[f'{{glyphs_{i},alpha_{i},{len(CHARS)},{size+8}}},' for i,size in enumerate((18,26,44))],
               '};', '#endif']
    (ROOT/'kernel/ui_font_data.h').write_text('\n'.join(output)+'\n')
    # Keep the legacy ASCII terminal intact; add Turkish Q glyphs in cells.
    extra='ÇçĞğİıÖöŞşÜüé£¬€₺'
    terminal=['/* Generated from OFL Selawik; Shenlong terminal extension. */',
              'static const struct { unsigned code; uint8_t rows[16]; } terminal_extra[] = {']
    font=ImageFont.truetype(str(ROOT/'assets/fonts/selawk.ttf'),14)
    for char in extra:
        canvas=Image.new('L',(16,18))
        ImageDraw.Draw(canvas).text((1,0),char,font=font,fill=255)
        bounds=canvas.getbbox()
        glyph=canvas.crop(bounds) if bounds else Image.new('L',(1,1))
        if glyph.width>8: glyph=glyph.resize((8,glyph.height),Image.Resampling.LANCZOS)
        target=Image.new('L',(8,16))
        target.paste(glyph,((8-glyph.width)//2,min(bounds[1] if bounds else 0,16-glyph.height)))
        if char=='₺' and not target.getbbox():
            # This older Selawik file predates the lira glyph. Original cell art.
            draw=ImageDraw.Draw(target)
            draw.line([(3,2),(3,13),(5,13),(7,10)],fill=255,width=1)
            draw.line([(1,7),(6,4)],fill=255,width=1)
            draw.line([(1,10),(6,7)],fill=255,width=1)
        rows=[sum((1<<(7-x)) for x in range(8) if target.getpixel((x,y))>=110) for y in range(16)]
        terminal.append('{'+str(ord(char))+', {'+','.join(f'0x{x:02x}' for x in rows)+'}},')
    terminal.append('};')
    (ROOT/'kernel/terminal_extra.h').write_text('\n'.join(terminal)+'\n')
    # A real outline font for the terminal, grayscale AA in fixed 10x24 cells.
    chars=''.join(chr(i) for i in range(32,127))+extra
    font=ImageFont.truetype(str(ROOT/'assets/fonts/NotoSansMono.ttf'),16*4)
    font.set_variation_by_axes([400,100])
    records=['/* Generated from Noto Sans Mono; assets/fonts/NotoSansMono-OFL.txt. */',
             '#ifndef TERMINAL_FONT_H', '#define TERMINAL_FONT_H',
             '#define TERMINAL_FONT_COUNT '+str(len(chars)),
             'static const struct { unsigned code; uint8_t alpha[240]; } terminal_font[] = {']
    for char in chars:
        canvas=Image.new('L',(40,96))
        advance=font.getlength(char)
        ImageDraw.Draw(canvas).text(((40-advance)/2,0),char,font=font,fill=255)
        canvas=canvas.resize((10,24),Image.Resampling.LANCZOS)
        records.append('{'+str(ord(char))+', {'+','.join(str(v) for v in canvas.tobytes())+'}},')
    records+=['};','#endif']
    (ROOT/'kernel/terminal_font.h').write_text('\n'.join(records)+'\n')

if __name__ == '__main__':
    main()
